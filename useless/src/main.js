// ---------- loop ----------
renderer.setAnimationLoop(() => {
  const now = performance.now();
  for (let i = anims.length - 1; i >= 0; i--) {
    const a = anims[i];
    const t = Math.min(1, (now - a.t0) / a.dur);
    a.set(a.from + (a.to - a.from) * a.e(t));
    if (t >= 1) { anims.splice(i, 1); a.resolve(); }
  }
  if (box && !switchOn && !busy && turnedOn > 2 && !idleSaid && now - lastTouch > 15000) {
    idleSaid = true;
    say(tr(turnedOn > 10 ? 'idle' : 'thanks'), 2200);
  }
  renderer.render(scene, camera);
});

