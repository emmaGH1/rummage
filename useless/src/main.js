const face = { eyes: [], brows: [], roll: 0, look: new THREE.Vector3(0, 1.5, 5), mood: 'smug' };
function buildFace() {
  const s = oracle.holder.scale.x;
  const W = oracle.size.x / s, H = oracle.size.y / s, D = oracle.size.z / s;
  const g = new THREE.Group();
  g.position.set(0, H * 0.5, D * 0.5 + 0.01 / s);
  oracle.holder.add(g);
  const r = 0.07 / s;
  const white = new THREE.MeshToonMaterial({ color: '#ffffff' }), black = new THREE.MeshBasicMaterial({ color: '#14121f' });
  for (const sx of [-1, 1]) {
    const eye = new THREE.Mesh(new THREE.SphereGeometry(r, 24, 16), white);
    eye.scale.z = 0.55; eye.position.x = sx * W * 0.2;
    const pupil = new THREE.Mesh(new THREE.SphereGeometry(r * 0.48, 16, 12), black);
    pupil.position.z = r * 0.42;
    eye.add(pupil);
    inkify(eye, { thickness: 0.006 });
    g.add(eye);
    face.eyes.push({ eye, pupil, r });
    const brow = new THREE.Mesh(new THREE.BoxGeometry(r * 2.1, r * 0.38, r * 0.4), black);
    brow.position.set(sx * W * 0.2, r * 1.45, r * 0.2);
    g.add(brow);
    face.brows.push({ brow, sx });
  }
  face.group = g;
}
async function eyeRoll() {
  if (!face.eyes.length || face.rolling) return;
  face.rolling = true;
  await tween((t) => (face.roll = t), 900, 0, 1, (t) => t);
  face.roll = 0; face.rolling = false;
}
function updateFace(now) {
  if (!face.eyes.length) return;
  for (const { eye, pupil, r } of face.eyes) {
    let dx, dy;
    if (face.roll > 0) { const a = Math.PI * 0.5 + face.roll * Math.PI * 2; dx = Math.cos(a) * 0.55; dy = Math.sin(a) * 0.55 + 0.1; }
    else {
      const p = eye.worldToLocal(face.look.clone()).normalize();
      dx = THREE.MathUtils.clamp(p.x * 1.4, -0.6, 0.6); dy = THREE.MathUtils.clamp(p.y * 1.4, -0.5, 0.6);
    }
    pupil.position.set(dx * r * 0.62, dy * r * 0.62, r * 0.42);
  }
  // brows: smug (one raised), angry (inner ends down), bored (low and flat)
  if (!face.rolling && performance.now() - progressAt < 9000 && !face.lookTap) face.look.copy(camera.position);
  const angry = face.mood === 'angry', bored = face.mood === 'bored';
  for (const { brow, sx } of face.brows) {
    const r = face.eyes[0].r;
    brow.rotation.z = angry ? sx * 0.45 : bored ? 0 : (sx > 0 ? -0.25 : 0.1);
    brow.position.y = r * (bored ? 1.05 : sx > 0 && !angry ? 1.75 : 1.45) + Math.sin(now / 300) * r * 0.04;
  }
}
