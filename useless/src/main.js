async function piece(slug, height, x, z, rotY = 0) {
  const robot = await loadArticulated(slug);
  await whenMeshesReady(robot);
  inkify(robot);
  addCavities(robot);
  const holder = new THREE.Group();
  robot.updateMatrixWorld(true);
  const box = new THREE.Box3().setFromObject(robot);
  const c = box.getCenter(new THREE.Vector3());
  robot.position.set(-c.x, -box.min.y, -c.z);
  holder.add(robot);
  holder.scale.setScalar(height / (box.max.y - box.min.y));
  holder.position.set(x, 0, z);
  holder.rotation.y = rotY;
  scene.add(holder);
  const parts = movableParts(slug, robot);
  for (const p of parts) {
    p.link = p.joint.children.find((ch) => ch.isURDFLink);
    fixDoorSwing(p, robot);
    p.link?.traverse((o) => o.isMesh && (o.userData.part = p));
  }
  robot.traverse((o) => o.isMesh && !o.userData.part && (o.userData.piece = slug));
  return { robot, holder, parts, size: box.getSize(new THREE.Vector3()).multiplyScalar(height / (box.max.y - box.min.y)) };
}

function fixDoorSwing(p, robot) {
  const ax = p.joint.axis;
  if (p.joint.jointType !== 'revolute' || Math.abs(ax.y) < 0.9) return;
  const centre = () => { robot.updateMatrixWorld(true); return robot.worldToLocal(new THREE.Box3().setFromObject(p.link).getCenter(new THREE.Vector3())); };
  const closed = centre(); p.joint.setJointValue(p.open); const opened = centre(); p.joint.setJointValue(0);
  if (opened.z < closed.z) p.open = -p.open;
}

