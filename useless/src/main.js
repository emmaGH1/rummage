const ray = new THREE.Raycaster();
canvas.addEventListener('pointerdown', async (e) => {
  if (!oracle || stage === 'loading' || stage === 'end') return;
  const v = new THREE.Vector2((e.clientX / innerWidth) * 2 - 1, -(e.clientY / innerHeight) * 2 + 1);
  ray.setFromCamera(v, camera);
  const hit = ray.intersectObjects(scene.children, true).find((h) => h.object.isMesh && (h.object.userData.part || h.object.userData.pc));
  if (!hit) return;
  let p = hit.object.userData.part;
  const pc = p ? p.pc : hit.object.userData.pc;
  if (pc.slug === 'u-box') return tapOracle();
  if (stage === 'busy') return;
  if (pc.slug === 'p-wardrobe' && stage === 'exit') return ending();
  if (pc.slug === 'p-wardrobe' && (stage === 'door1' || stage === 'door2')) return onOpen(pc.parts[0]);
  if (!p) p = pc.parts.find((q) => !isOpen(q)) || pc.parts[0]; // tapping the body opens the next closed part
  if (!p) return;
  if (isOpen(p)) {
    sfx(p.joint.jointType === 'prismatic' ? 'slide' : 'shut');
    await jointTo(p, 0, 260);
    onClose(p);
  } else {
    sfx(p.joint.jointType === 'prismatic' ? 'slide' : 'creak');
    await jointTo(p, p.open, 300);
    onOpen(p);
  }
});

// ================= loop =================
function handTo(target, dur) {
  const from = hand.position.clone();
  return tween((t) => hand.position.lerpVectors(from, target, t), dur);
}
renderer.setAnimationLoop(() => {
  const now = performance.now();
  for (let i = anims.length - 1; i >= 0; i--) {
    const a = anims[i];
    const t = Math.min(1, (now - a.t0) / a.dur);
    a.set(a.from + (a.to - a.from) * a.e(t));
    if (t >= 1) { anims.splice(i, 1); a.resolve(); }
  }
  if (stage !== 'end') hud();
  sign.scale.setScalar(stage === 'door1' || stage === 'exit' || stage === 'door2' ? 1 + Math.sin(now / 160) * 0.06 : 1);
  renderer.render(scene, camera);
});

