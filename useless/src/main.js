async function turnOff(mood) {
  const speed = mood === 'angry' ? 0.45 : mood === 'sleepy' ? 2.2 : 1;
  if (mood === 'sleepy') { say(line(['zzz… huh?', 'zzz……嗯？']), 1400); await wait(1500); }
  if (mood === 'fake') {
    sfx('creak');
    await jointTo(lid, lid.open * 0.25, 260);
    await wait(500);
    sfx('shut');
    await jointTo(lid, 0, 160);
    say(line(['…', '……']), 900);
    await wait(1300);
    if (!switchOn) return; // they gave up, the box wins anyway
  }
  // drumroll before the revelation
  if (mood !== 'angry') for (let i = 0; i < 6; i++) { sfx('tick'); await wait(110 - i * 8); }
  sfx(mood === 'angry' ? 'chomp' : 'creak');
  await jointTo(lid, lid.open, (mood === 'angry' ? 320 : 700) * speed);
  hand.visible = true;
  if (mood === 'wave') {
    await handTo(handUp, 300);
    for (let i = 0; i < 3; i++) {
      await tween((a) => (hand.rotation.z = a), 140, -0.5, 0.5);
      await tween((a) => (hand.rotation.z = a), 140, 0.5, -0.5);
    }
    hand.rotation.z = 0;
    say(line(['hi! anyway.', '嗨！总之。']), 1100);
  } else {
    await handTo(handUp, 260 * speed);
  }
  // Lux3D put the switch on the lid, so it rides up with it: aim at wherever it is now
  if (sw3d) {
    box.robot.updateMatrixWorld(true);
    const w = new THREE.Box3().setFromObject(sw3d.link).getCenter(new THREE.Vector3());
    const local = box.holder.worldToLocal(w);
    handPress.copy(local).lerp(handUp, 0.35);
    const dir = local.clone().sub(handUp);
    hand.rotation.y = Math.atan2(dir.x, dir.z) + (window.HAND_YAW ?? Math.PI / 2);
  }
  // the revelation
  const text = revealFact();
  await wait(1700 + text.length * (LANG === 'zh' ? 110 : 45));
  await handTo(handPress, 200 * speed);
  // click
  sfx('click');
  setSwitch(false);
  turnedOff++;
  stats();
  await handTo(handUp, 180 * speed);
  await handTo(handRest, 240 * speed);
  hand.visible = false;
  sfx('shut');
  await jointTo(lid, 0, mood === 'angry' ? 110 : 220 * speed);
}

async function cabinetHelps() {
  // the cabinet joins in: doors fly open, drawer shoots out
  const doors = cab.parts.filter((p) => p.joint.jointType === 'revolute');
  const drawer = cab.parts.find((p) => p.joint.jointType === 'prismatic');
  say(line(['the cabinet would like to confirm this fact.', '柜子表示同意这条真理。']), 1800);
  sfx('creak');
  await Promise.all(doors.map((d) => jointTo(d, d.open, 260)));
  if (drawer) { sfx('slide'); await jointTo(drawer, drawer.open, 240); }
  await wait(600);
  sfx('shut');
  await Promise.all([...doors, drawer].filter(Boolean).map((d) => jointTo(d, 0, 200)));
}

function pickMood(n) {
  if (n === 1) return 'normal';
  if (n === 4) return 'fake';
  if (n === 6) return 'angry';
  if (n === 9) return 'wave';
  if (n === 12) return 'sleepy';
  if (n < 6) return 'normal';
  return ['normal', 'angry', 'angry', 'fake', 'wave', 'sleepy', 'normal'][Math.floor(Math.random() * 7)];
}

async function flip() {
  lastTouch = performance.now(); idleSaid = false;
  if (switchOn || !box) return;
  setSwitch(true);
  $('#fact').classList.remove('on');
  sfx('tick');
  turnedOn++;
  stats();
  if (busy) return;
  busy = true;
  try {
    while (switchOn) {
      const n = turnedOn;
      if (n === 8 || (n > 12 && n % 10 === 0)) await cabinetHelps();
      await wait(n === 1 ? 700 : 250 + Math.random() * 500);
      await turnOff(pickMood(n));
    }
  } finally { busy = false; }
}
