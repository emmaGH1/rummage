const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const ease = (t) => (t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2);
function tween(set, dur, from = 0, to = 1, e = ease) {
  return new Promise((resolve) => anims.push({ set, from, to, t0: performance.now(), dur, e, resolve }));
}
function jointTo(p, v, dur) {
  const from = p.value;
  return tween((x) => { p.value = x; p.joint.setJointValue(x); }, dur, from, v);
}
function handTo(target, dur, e = ease) {
  const from = hand.position.clone();
  return tween((t) => hand.position.lerpVectors(from, target, t), dur, 0, 1, e);
}

