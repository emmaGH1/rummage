function tween(set, dur, from = 0, to = 1, e = ease) {
  return new Promise((resolve) => anims.push({ set, from, to, t0: performance.now(), dur, e, resolve }));
}
function jointTo(p, v, dur = 320) {
  const from = p.value;
  return tween((x) => { p.value = x; p.joint.setJointValue(x); }, dur, from, v);
}
